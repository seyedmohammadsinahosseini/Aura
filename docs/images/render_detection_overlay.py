#!/usr/bin/env python3
"""Generate the two labelled synthetic images that ship in this repository.

    docs/images/detection-overlay.png  — an annotated 1920x1080 frame
    docs/images/dashboard-concept.png  — the admin dashboard, as a concept

WHY SYNTHETIC: the real thing needs an Ada GPU, the private TRT engines, live cameras and
the proprietary ``log-entry`` dependency. None of that exists here, and fabricating a
capture from a real deployment would be dishonest. So these pictures are clearly marked as
generated, in the image itself as well as in docs/SCREENSHOTS.md.

The overlay is not decorative guesswork: it calls OpenCV the way the production drawers do,
with the same colours, font, scale, thickness and label grammar read from

    modules/draw/DetectionDrawer.cpp     green box, thickness 3
    modules/draw/RecognitionDrawer.cpp   two lines above the box, name [PASS|FAIL] + flags
    modules/draw/ModuleHudDrawer.cpp     MODULES panel, ON green / OFF red

so the typography you see is what the pipeline really puts on a frame.

Usage:  python3 docs/images/render_detection_overlay.py [--check]
"""
from __future__ import annotations

import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT_OVERLAY = HERE / "detection-overlay.png"
OUT_DASHBOARD = HERE / "dashboard-concept.png"

W, H = 1920, 1080

# --- exactly the constants used by RecognitionDrawer::draw ------------------------------
FONT = None  # filled in below with cv2.FONT_HERSHEY_SIMPLEX
FONT_SCALE = 0.9
THICKNESS = 3
LINE_GAP = 28
GREEN = (0, 255, 0)
RED = (0, 0, 255)
HUD_ON = (0, 200, 0)
HUD_OFF = (0, 0, 200)

CAPTION = ("SYNTHETIC IMAGE - generated by docs/images/render_detection_overlay.py, "
           "not a capture from a real deployment")


def scene(rng: np.random.Generator):
    """A bland office corridor: gradient walls, desks, and three soft human silhouettes."""
    import cv2
    import numpy as np

    frame = np.zeros((H, W, 3), np.uint8)
    for y in range(H):                                   # vertical ambient gradient
        t = y / H
        frame[y, :] = (int(46 + 40 * t), int(52 + 44 * t), int(60 + 50 * t))

    cv2.rectangle(frame, (0, int(H * 0.62)), (W, H), (58, 62, 70), -1)      # floor
    cv2.line(frame, (0, int(H * 0.62)), (W, int(H * 0.62)), (86, 92, 100), 2)
    for x in (140, 620, 1180, 1700):                      # wall panels / doors
        cv2.rectangle(frame, (x, 120), (x + 260, int(H * 0.62)),
                      (66, 72, 80), 3)
    for x, y, w, h in ((120, 720, 420, 150), (980, 700, 520, 170)):          # desks
        cv2.rectangle(frame, (x, y), (x + w, y + h), (92, 78, 62), -1)
    for i in range(240):                                   # sensor noise
        x, y = int(rng.integers(0, W)), int(rng.integers(0, H))
        frame[y, x] = np.clip(frame[y, x].astype(int) + rng.integers(-18, 18), 0, 255)
    return frame


def figures(rng: np.random.Generator):
    """Returns (frame, boxes): three people at different distances/side-angles."""
    import cv2
    import numpy as np

    frame = scene(rng)
    specs = [  # (center_x, head_top_y, head_radius, side_angle_deg, blur_px)
        (520, 300, 96, 0, 0),
        (1130, 372, 74, 55, 5),
        (1560, 452, 52, 12, 9),
    ]
    boxes = []
    for cx, top, r, yaw, blur in specs:
        person = np.zeros((H, W, 3), np.uint8)
        body_w = int(r * 2.6)
        cv2.ellipse(person, (cx, top + int(r * 3.4)), (body_w // 2, int(r * 2.6)), 0, 0, 360,
                    (150, 150, 158), -1)                    # torso
        cv2.ellipse(person, (cx, top + r), (int(r * (1.0 if yaw < 30 else 0.78)), r), 0, 0, 360,
                    (176, 160, 146), -1)                     # head
        if blur:
            person = cv2.GaussianBlur(person, (0, 0), blur)
        mask = person.sum(axis=2) > 20
        frame[mask] = (0.75 * frame[mask] + 0.25 * person[mask]).astype(np.uint8)
        pad = int(r * 0.35)
        boxes.append((cx - int(r * 1.25) - pad, top - pad,
                      cx + int(r * 1.25) + pad, top + r * 2 + pad))
    frame = cv2.GaussianBlur(frame, (3, 3), 0)              # encode/decode softness
    return frame, boxes


def label_line(cv2, frame, text, origin, color):
    """RecognitionDrawer draws text directly onto the frame; a thin shadow keeps it legible."""
    cv2.putText(frame, text, (origin[0] + 2, origin[1] + 2), cv2.FONT_HERSHEY_SIMPLEX,
                FONT_SCALE, (0, 0, 0), THICKNESS + 2, cv2.LINE_AA)
    cv2.putText(frame, text, origin, cv2.FONT_HERSHEY_SIMPLEX, FONT_SCALE, color, THICKNESS,
                cv2.LINE_AA)
    return cv2.getTextSize(text, cv2.FONT_HERSHEY_SIMPLEX, FONT_SCALE, THICKNESS)[0]


def draw_people(cv2, frame, boxes):
    """One detection box + the two recognition lines, in the production format."""
    rows = [("Sina Hosseini", True, 62, False, False),
            ("Ali Rezaei", True, 71, True, False),
            ("Person#41", False, 44, False, True)]
    for (x0, y0, x1, y1), (name, ok, blur, side, far) in zip(boxes, rows):
        cv2.rectangle(frame, (x0, y0), (x1, y1), GREEN if ok else RED, 3, cv2.LINE_AA)

        color = GREEN if ok else RED
        flags = ""
        if side:
            flags += "  SIDE"
        if far:
            flags += "  FAR"
        line1 = f"{name} [{'PASS' if ok else 'FAIL'}]"
        w1 = label_line(cv2, frame, line1, (x0, y0 - LINE_GAP - 26), color)

        line2 = f"BLUR:{blur}"
        label_line(cv2, frame, line2, (x0, y0 - LINE_GAP), GREEN if blur > 50 else RED)
        width = cv2.getTextSize(line2, cv2.FONT_HERSHEY_SIMPLEX, FONT_SCALE, THICKNESS)[0][0]
        if flags:
            label_line(cv2, frame, flags, (x0 + width + 6, y0 - LINE_GAP), RED)
        _ = w1


def draw_hud(cv2, frame, statuses):
    """A near-transparent MODULES panel, matching ModuleHudDrawer's box and rows."""
    header = "MODULES"
    (tw, th), _ = cv2.getTextSize(header, cv2.FONT_HERSHEY_SIMPLEX, 0.9, 2)
    widths = [tw]
    for name, on in statuses:
        widths.append(cv2.getTextSize(name, cv2.FONT_HERSHEY_SIMPLEX, 0.7, 2)[0][0] +
                      cv2.getTextSize("ON" if on else "OFF", cv2.FONT_HERSHEY_SIMPLEX,
                                      0.7, 2)[0][0])
    box_w = max(widths) + 44
    box_h = 50 + 36 * len(statuses) + 22
    cv2.rectangle(frame, (16, 16), (16 + box_w, 16 + box_h), (0, 0, 0), -1)
    cv2.rectangle(frame, (16, 16), (16 + box_w, 16 + box_h), (60, 60, 60), 1)
    cv2.putText(frame, header, (26, 50), cv2.FONT_HERSHEY_SIMPLEX, 0.9, (255, 255, 255), 2,
                cv2.LINE_AA)
    y = 92
    for name, on in statuses:
        cv2.putText(frame, name, (26, y), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (235, 235, 235), 2,
                    cv2.LINE_AA)
        w = cv2.getTextSize(name, cv2.FONT_HERSHEY_SIMPLEX, 0.7, 2)[0][0]
        cv2.putText(frame, "ON" if on else "OFF", (26 + w + 14, y), cv2.FONT_HERSHEY_SIMPLEX,
                    0.7, HUD_ON if on else HUD_OFF, 2, cv2.LINE_AA)
        y += 36


def render_overlay() -> None:
    import cv2
    import numpy as np

    rng = np.random.default_rng(7)
    frame, boxes = figures(rng)
    draw_people(cv2, frame, boxes)
    draw_hud(cv2, frame, [("detection", True), ("tracking", True), ("recognition", True),
                          ("attendance", True), ("face_crop", True), ("anti_saturation", False)])

    # watermark, bottom-left, deliberately understated
    cv2.rectangle(frame, (0, H - 46), (W, H), (12, 12, 12), -1)
    cv2.putText(frame, CAPTION, (16, H - 16), cv2.FONT_HERSHEY_SIMPLEX, 0.62, (200, 200, 200),
                1, cv2.LINE_AA)
    cv2.imwrite(str(OUT_OVERLAY), cv2.resize(frame, (1440, 810),
                                             interpolation=cv2.INTER_AREA))
    print(f"  wrote {OUT_OVERLAY.relative_to(HERE.parent.parent)}")


def render_dashboard() -> None:
    """Concept art for the admin dashboard: what the Vue app shows, not a screenshot of it."""
    from PIL import Image, ImageDraw, ImageFont

    S = 2
    Wd, Hd = 1400 * S, 950 * S
    img = Image.new("RGB", (Wd, Hd), (246, 247, 250))
    d = ImageDraw.Draw(img)
    f = lambda px: ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
                                       px * S)
    fb = lambda px: ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
                                        px * S)
    ink, mut, line, brand = (31, 41, 55), (107, 114, 128), (226, 230, 236), (37, 99, 235)

    d.rectangle([0, 0, Wd, 64 * S], fill=(17, 24, 39))
    d.text((24 * S, 22 * S), "FaceAuth Attendance", font=f(19), fill=(255, 255, 255))
    for i, nav in enumerate(["Live", "Persons", "Attendance", "Cameras", "Review queue",
                             "Settings"]):
        d.text((250 * S + i * 150 * S, 24 * S), nav, font=fb(15) if i == 0 else f(15),
               fill=(255, 255, 255) if i == 0 else (148, 163, 184))
    d.rounded_rectangle([Wd - 300 * S, 18 * S, Wd - 64 * S, 48 * S], radius=8 * S,
                        outline=(248, 113, 113), width=1 * S)
    d.text((Wd - 288 * S, 23 * S), "concept mockup — not the real UI", font=f(12),
           fill=(252, 165, 165))
    d.ellipse([Wd - 44 * S, 22 * S, Wd - 20 * S, 46 * S], fill=brand)
    d.text((Wd - 40 * S, 24 * S), "SN", font=fb(12), fill=(255, 255, 255))

    d.text((24 * S, 90 * S), "Live", font=fb(26), fill=ink)
    d.text((24 * S, 126 * S), "4 cameras · 2 streaming · pipeline running on GPU-0",
           font=f(14), fill=mut)

    tiles = [("Entrance cam 01", True, "Sina Hosseini  PASS", "10:04:12"),
             ("Entrance cam 02", True, "unknown  FAIL", "10:04:12"),
             ("Back office", False, "no signal", ""),
             ("Warehouse door", False, "paused", "")]
    for i, (name, live, tag, stamp) in enumerate(tiles):
        x0 = 24 * S + (i % 2) * (420 * S)
        y0 = 170 * S + (i // 2) * (232 * S)
        x1, y1 = x0 + 400 * S, y0 + 214 * S
        d.rounded_rectangle([x0, y0, x1, y1], radius=10 * S, fill=(17, 24, 39), outline=line)
        if live:
            for k in range(9):
                d.rectangle([x0 + 8 * S, y0 + 8 * S + k * 23 * S, x1 - 8 * S,
                              y0 + 20 * S + k * 23 * S],
                            fill=(26 + 4 * (k % 3), 32 + 4 * (k % 3), 44 + 4 * (k % 3)))
            cx, cy = x0 + 200 * S, y0 + 110 * S
            d.ellipse([cx - 26 * S, cy - 44 * S, cx + 26 * S, cy + 8 * S], fill=(120, 128, 140))
            d.ellipse([cx - 46 * S, cy + 6 * S, cx + 46 * S, cy + 96 * S], fill=(96, 104, 116))
            d.rectangle([cx - 40 * S, cy - 52 * S, cx + 40 * S, cy + 20 * S], outline=(0, 255, 0),
                        width=2 * S)
        else:
            d.text((x0 + 130 * S, y0 + 96 * S), "— no frame —", font=f(15), fill=(100, 110, 128))
        d.text((x0 + 14 * S, y0 + 186 * S), name, font=fb(13), fill=(226, 232, 240))
        d.text((x0 + 250 * S, y0 + 186 * S), tag, font=f(12),
               fill=(74, 222, 128) if "PASS" in tag else (248, 113, 113))
        if stamp:
            d.text((x1 - 96 * S, y0 + 14 * S), stamp, font=f(12), fill=(148, 163, 184))

    px0, py0 = 900 * S, 170 * S
    d.rounded_rectangle([px0, py0, px0 + 476 * S, py0 + 232 * S], radius=10 * S, fill="white",
                        outline=line)
    d.text((px0 + 18 * S, py0 + 16 * S), "Today", font=fb(17), fill=ink)
    d.line([px0, py0 + 50 * S, px0 + 476 * S, py0 + 50 * S], fill=line, width=1 * S)
    for i, (who, when, kind) in enumerate([("Sina Hosseini", "08:01:14", "IN"),
                                           ("Ali Rezaei", "08:04:02", "IN"),
                                           ("Maryam K.", "08:12:55", "IN"),
                                           ("Sina Hosseini", "12:00:31", "BREAK")]):
        yy = py0 + 66 * S + i * 40 * S
        d.text((px0 + 18 * S, yy), when, font=f(14), fill=mut)
        d.text((px0 + 128 * S, yy), who, font=f(14), fill=ink)
        c = brand if kind == "IN" else (234, 88, 12)
        d.rounded_rectangle([px0 + 380 * S, yy - 2 * S, px0 + 444 * S, yy + 24 * S],
                            radius=6 * S, outline=c)
        d.text((px0 + 392 * S, yy + 2 * S), kind, font=fb(11), fill=c)

    qy = py0 + 256 * S
    d.rounded_rectangle([px0, qy, px0 + 476 * S, qy + 146 * S], radius=10 * S, fill="white",
                        outline=line)
    d.text((px0 + 18 * S, qy + 16 * S), "Review queue", font=fb(17), fill=ink)
    d.text((px0 + 18 * S, qy + 50 * S), "3 unknown faces · nothing is auto-attributed",
           font=f(13), fill=mut)
    for i, (score, q) in enumerate([("44%", "BLUR"), ("38%", "SIDE"), ("51%", "FAR")]):
        bx = px0 + 18 * S + i * 108 * S
        d.rounded_rectangle([bx, qy + 82 * S, bx + 96 * S, qy + 128 * S], radius=6 * S,
                            fill=(17, 24, 39))
        d.text((bx + 10 * S, qy + 90 * S), f"{score} {q}", font=f(11), fill=(226, 232, 240))

    d.rounded_rectangle([24 * S, 660 * S, 1376 * S, 926 * S], radius=10 * S, fill="white",
                        outline=line)
    d.text((42 * S, 678 * S), "This is concept art, not a screenshot", font=fb(17),
           fill=(220, 38, 38))
    d.multiline_text((42 * S, 716 * S),
                     "Drawn by docs/images/render_detection_overlay.py to communicate what the\n"
                     "Vue 3 + Vite admin panel does: live tiles from GET /api/stream/<uid> (MJPEG),\n"
                     "today's rows from GET /api/logs/today, and the unknown-face queue from\n"
                     "GET /api/unknown-faces/pending. Real screenshots live in docs/images/ once\n"
                     "scripts/capture_screenshots.sh is run on a machine with a GPU and cameras.",
                     font=f(13), fill=mut, spacing=8)
    img = img.resize((Wd // S, Hd // S), Image.LANCZOS)
    img.save(OUT_DASHBOARD)
    print(f"  wrote {OUT_DASHBOARD.relative_to(HERE.parent.parent)}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the images are missing")
    args = ap.parse_args()
    if args.check:
        for f in (OUT_OVERLAY, OUT_DASHBOARD):
            if not f.exists():
                raise SystemExit(f"missing {f.name} — run render_detection_overlay.py")
            print(f"ok  {f.name} present")
        return 0
    render_overlay()
    render_dashboard()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
